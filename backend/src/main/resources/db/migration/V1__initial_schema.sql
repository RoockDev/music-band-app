CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255),
    role VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    token_version BIGINT NOT NULL,
    minor BOOLEAN NOT NULL,
    guardian_contact VARCHAR(255),
    consent_on_file BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT,
    CONSTRAINT pk_user_account PRIMARY KEY (id),
    CONSTRAINT uk_user_account_email UNIQUE (email),
    CONSTRAINT ck_user_account_role CHECK (role IN ('MUSICIAN', 'ADMIN')),
    CONSTRAINT ck_user_account_status CHECK (status IN ('PENDING', 'ACTIVE', 'DEACTIVATED')),
    CONSTRAINT ck_user_account_token_version CHECK (token_version >= 0),
    CONSTRAINT ck_user_account_minor_fields CHECK (
        (minor AND guardian_contact IS NOT NULL AND BTRIM(guardian_contact) <> '' AND consent_on_file)
        OR (NOT minor AND guardian_contact IS NULL AND NOT consent_on_file)
    )
);

CREATE TABLE password_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    type VARCHAR(255) NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT,
    CONSTRAINT pk_password_token PRIMARY KEY (id),
    CONSTRAINT uk_password_token_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_password_token_type CHECK (type IN ('ACTIVATION', 'RESET')),
    CONSTRAINT ck_password_token_expiry CHECK (expires_at > created_at),
    CONSTRAINT fk_password_token_user FOREIGN KEY (user_id) REFERENCES user_account (id)
);

CREATE TABLE admin_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
