    permission VARCHAR(255) NOT NULL,
    CONSTRAINT pk_admin_permission PRIMARY KEY (id),
    CONSTRAINT uk_admin_permission_admin_permission UNIQUE (admin_id, permission),
    CONSTRAINT ck_admin_permission_permission CHECK (permission IN (
        'MANAGE_USERS',
