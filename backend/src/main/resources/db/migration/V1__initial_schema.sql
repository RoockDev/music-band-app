        'MANAGE_GROUPS',
        'MANAGE_SHEET_MUSIC',
        'MANAGE_EVENTS',
        'MANAGE_CONTENT'
    )),
    CONSTRAINT fk_admin_permission_admin FOREIGN KEY (admin_id) REFERENCES user_account (id)
);

